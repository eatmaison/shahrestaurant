// Generate delivery copies only; the approved PNG masters remain untouched.
import fs from "node:fs/promises";
import crypto from "node:crypto";
import sharp from "sharp";

const directory = "public/brand/edited-restaurant-photos-v1";
const inputs = [
  { name: "atmosphere-setting-v2", alias: "/brand/shah-atmosphere-v1.webp", master: "assets/imagegen/shah-atmosphere-setting-v2.png", widths: [320, 640, 960] },
  { name: "room-setting-v3", alias: "/brand/shah-room-v1.webp", master: "assets/imagegen/shah-room-setting-v3.png", widths: [320, 640, 960] },
  { name: "dining", alias: "/brand/shah-dining-v1.webp", master: "assets/imagegen/shah-dining-focus-v3.png" },
  { name: "kitchen", alias: "/brand/shah-table-v1.webp", master: "assets/imagegen/shah-kitchen-focus-v1.png" },
  { name: "bar-shine", alias: "/brand/shah-bar-v1.webp", master: "assets/imagegen/shah-bar-shine-v1.png", widths: [320, 640, 960] },
];
const hash = bytes => crypto.createHash("sha256").update(bytes).digest("hex");
const records = {}, evidence = [];
sharp.concurrency(2);
await fs.mkdir(directory, { recursive: true });
for (const input of inputs) {
  const original = await fs.readFile(input.master), meta = await sharp(original).metadata();
  const widths = (input.widths ?? [320, 640, 960, 1400]).filter(width => width <= meta.width);
  const formats = { avif: [], webp: [], jpeg: [] }, outputs = [];
  for (const width of widths) for (const format of Object.keys(formats)) {
    let selected;
    const qualities = format === "avif" ? [62, 58, 54, 50] : input.widths ? [84, 80, 76, 72, 68, 64, 60] : [84, 80, 76, 72];
    for (const quality of qualities) {
      const image = sharp(original).rotate().resize({ width, withoutEnlargement: true }).toColourspace("srgb");
      const bytes = await image[format]({ quality, ...(format === "avif" ? { effort: 5 } : format === "webp" ? { effort: 6 } : { mozjpeg: true }) }).toBuffer();
      if (bytes.length >= 200000) continue;
      const size = await sharp(bytes).metadata(), extension = format === "jpeg" ? "jpg" : format;
      const src = `/brand/edited-restaurant-photos-v1/${input.name}-${width}.${extension}`;
      await fs.writeFile("public" + src, bytes);
      selected = { src, width: size.width, height: size.height, bytes: bytes.length };
      formats[format].push(selected); outputs.push({ ...selected, quality, sha256: hash(bytes) });
      break;
    }
    if (!selected) throw new Error(`Delivery budget exceeded: ${input.name} ${width} ${format}`);
  }
  const largest = formats.webp.at(-1), jpeg = formats.jpeg.at(-1);
  const srcset = entries => entries.map(item => `${item.src} ${item.width}w`).join(", ");
  const blur = await sharp(original).resize({ width: 20 }).blur(0.6).webp({ quality: 30 }).toBuffer();
  records[input.alias] = {
    width: largest.width, height: largest.height, src: largest.src,
    avifSrcSet: srcset(formats.avif), webpSrcSet: srcset(formats.webp),
    blurDataURL: "data:image/webp;base64," + blur.toString("base64"),
    avif: formats.avif, webp: formats.webp,
    jpeg: { src: jpeg.src, srcSet: srcset(formats.jpeg), width: jpeg.width, height: jpeg.height },
  };
  evidence.push({ ...input, originalDimensions: { width: meta.width, height: meta.height }, masterSha256: hash(original), outputs });
}
await fs.writeFile("app/lib/editedRestaurantPhotos.ts", `// Generated by scripts/generate-edited-restaurant-photos.mjs.\nimport type { RestaurantPhoto } from "./restaurantPhotos";\nimport type { JpegPhotoFallback } from "./restaurantPhotoJpegFallbacks";\ntype EditedPhoto = RestaurantPhoto & { jpeg: JpegPhotoFallback };\nconst photos: Readonly<Record<string, EditedPhoto>> = ${JSON.stringify(records, null, 2)};\nconst aliases: Readonly<Record<string, string>> = { "/photos/687A0402.jpeg": "/brand/shah-dining-v1.webp", "/photos/687A0412.jpeg": "/brand/shah-table-v1.webp", "/photos/687A0343.jpeg": "/brand/shah-bar-v1.webp", "/photos/687A0210.jpeg": "/brand/shah-room-v1.webp", "/photos/687A0336.jpeg": "/brand/shah-atmosphere-v1.webp" };\nexport function getEditedRestaurantPhoto(src: string): EditedPhoto | undefined { const key = Object.prototype.hasOwnProperty.call(aliases, src) ? aliases[src] : src; return Object.prototype.hasOwnProperty.call(photos, key) ? photos[key] : undefined; }\n`);
await fs.writeFile("docs/edited-restaurant-photo-assets-2026-11-13.json", JSON.stringify({ encoder: sharp.versions.sharp, maximumDeliveryBytes: 200000, photos: evidence }, null, 2));
console.log(JSON.stringify(evidence.map(item => ({ master: item.master, outputs: item.outputs.length, maximumBytes: Math.max(...item.outputs.map(output => output.bytes)) }))));
